"""Generate full 256-branch dependent eliminator and induction proofs.
Every branch is present. Lean kernel checks all constructor cases; this is
finite exhaustive proof, not input sampling.
"""
from pathlib import Path
W=Path(__file__).resolve().parent
def groups(xs,n=12):
 return '\n'.join('    '+' '.join(xs[i:i+n]) for i in range(0,len(xs),n))
hs=['h'+str(i) for i in range(256)]
args=groups(hs)
def binders(sort):
 return '(P : Fin 256 → '+sort+')\n'+groups(['('+h+' : P '+str(i)+')' for i,h in enumerate(hs)],4)
body='Fin.elim0 i'
for h in reversed(hs):body='Fin.cases '+h+' (fun i => '+body+') i'
s='''-- Generated by generate_byte_elimination.py.
import ByteOperations
set_option autoImplicit false
set_option maxRecDepth 8192
set_option maxHeartbeats 4000000
noncomputable section
namespace NativeBridge.Incremental.ByteElimination
open NativeBridge
universe u
'''
s+='def finByteRec '+binders('Sort u')+' (b : Fin 256) : P b :=\n  (fun i => '+body+') b\n'
for suffix,sort in [('rect','Sort u'),('rec','Type')]:
 s+='\ntheorem byte_'+suffix+'_agrees '+binders(sort)+' (b : Rocq.Corelib.Init.Byte.byte) :\n'
 s+='    Rocq.Corelib.Init.Byte.byte_'+suffix+' (fun b => P (byteTo b))\n'+args+' b =\n      finByteRec P\n'+args+' (byteTo b) := by\n  cases b <;> rfl\n'
s+='\ndef byteInduction : Prop :=\n  ∀ P : Fin 256 → Prop,\n'
s+=groups(['P '+str(i)+' →' for i in range(256)],8)+'\n    ∀ b, P b\n'
s+='theorem byte_ind_native : byteInduction :=\n  fun P '+ ' '.join(hs)+' b => finByteRec P\n'+args+' b\n'
s+='theorem byte_ind_proof : Rocq.Corelib.Init.Byte.byte_ind.statement := by\n  intro P '+ ' '.join(hs)+' b\n'
s+='  exact Rocq.Corelib.Init.Byte.byte.rec (motive := P)\n'+args+' b\n'
s+='''
theorem byte_sind_proof : Rocq.Corelib.Init.Byte.byte_sind.statement := byte_ind_proof
theorem byte_ind_correspondence : Rocq.Corelib.Init.Byte.byte_ind.statement ↔ byteInduction :=
  ⟨fun _ => byte_ind_native,fun _ => byte_ind_proof⟩
theorem byte_sind_correspondence : Rocq.Corelib.Init.Byte.byte_sind.statement ↔ byteInduction :=
  ⟨fun _ => byte_ind_native,fun _ => byte_sind_proof⟩
end NativeBridge.Incremental.ByteElimination
'''
import json,re
names=sorted({sp['native_target'] for sp in json.loads((W/'certificates.json').read_text()) if sp['profile']=='ByteElimination'})
footer=(W/'proofs/BinaryDivision.lean').read_text().split('\nopen Lean Meta Elab Command')[1]
footer=re.sub(r'for name in \[.*\] do','for name in '+json.dumps(names)+' do',footer)
s+='\nopen Lean Meta Elab Command'+footer
(W/'proofs/ByteElimination.lean').write_text(s)
