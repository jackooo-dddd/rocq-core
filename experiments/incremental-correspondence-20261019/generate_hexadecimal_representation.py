"""Instantiate the proved digit-representation scheme for the actual hexadecimal
closure. Its exponent is decimal, not hexadecimal. Generated proofs are
independently kernel-checked; shared helper text adds no coverage roots.
"""
from pathlib import Path
import re
W=Path(__file__).resolve().parent
R=W.parents[1]
s=(W/'proofs/DecimalRepresentation.lean').read_text().split('\nopen Lean Meta Elab Command')[0]
start=s.index('theorem uint_of_uint_agrees')
end=s.index('-- Extract only',start)
s=s[:start]+s[end:]
s=s.replace('decimal','hexadecimal').replace('Decimal','Hexadecimal')
s=re.sub(r'(?<![0-9])10(?![0-9])','16',s)
s='-- Generated by generate_hexadecimal_representation.py; independently checked.\n'+s
# The exponent retains decimal digits and its own sign.
base=(R/'experiments/mechanical-correspondence-20261019/DecimalDigits.lean').read_text()
digits=base[base.index('def decimalDigitsTo'):base.index('\n',base.index('def decimalDigitsIso'))]
ops=(W/'proofs/DecimalOperations.lean').read_text()
signed=ops[ops.index('def signedTo'):ops.index('theorem abs_agrees')]
beq=ops[ops.index('def digitBoolTo'):ops.index('/-- Canonicalize')]
exp='''namespace Exponent
abbrev U := Rocq.Corelib.Init.Decimal.uint
abbrev S := Rocq.Corelib.Init.Decimal.signed_int
'''+digits+'\n'+signed+'\n'+beq+'\nend Exponent\n'
s=s.replace('abbrev SignedDigits',exp+'\nabbrev SignedDigits',1)
s=s.replace('Option SignedDigits','Option (Bool × List (Fin 10))')
s=s.replace('some (signedTo e)','some (Exponent.signedTo e)')
s=s.replace('(signedOf e)','(Exponent.signedOf e)')
s=s.replace('hexadecimalTo,signed_of_to]','hexadecimalTo,signed_of_to,Exponent.signed_of_to]')
s=s.replace('hexadecimalTo,signed_to_of]','hexadecimalTo,signed_to_of,Exponent.signed_to_of]')
expeq='''theorem exponent_beq_agrees (x y : Rocq.Corelib.Init.Decimal.signed_int) :
    digitBoolTo (Rocq.Corelib.Init.Decimal.signed_int_beq x y) =
      (Exponent.signedTo x == Exponent.signedTo y) := Exponent.signed_int_beq_agrees x y
'''
s=s.replace('def hexadecimalEqual',expeq+'\ndef hexadecimalEqual')
s=s.replace('signed_int_beq_agrees,uint_beq_agrees]','signed_int_beq_agrees,uint_beq_agrees,exponent_beq_agrees]')
s=s.replace('  | D9 d ih => rfl\n',''.join('  | D'+format(k,'x')+' d ih => rfl\n' for k in range(9,16)))
# Reinstantiate the finite carry proof.
start=s.index('theorem little_double_pair')
end=s.index('theorem little_double_agrees',start)
block='''theorem little_double_pair (d : U) :
    hexadecimalDigitsTo (Rocq.Corelib.Init.Hexadecimal.Little.double d) = littleDouble false (hexadecimalDigitsTo d) ∧
    hexadecimalDigitsTo (Rocq.Corelib.Init.Hexadecimal.Little.succ_double d) = littleDouble true (hexadecimalDigitsTo d) := by
  induction d with
  | Nil => exact ⟨rfl,rfl⟩
'''
for k in range(16):
 fn='double' if k<8 else 'succ_double';ih='1' if k<8 else '2';carry='false' if k<8 else 'true'
 block+='  | D'+format(k,'x')+' d ih =>\n    constructor\n'
 for digit in [2*k%16,(2*k+1)%16]:
  block+=f'''    · change ({digit} : Fin 16) :: hexadecimalDigitsTo (Rocq.Corelib.Init.Hexadecimal.Little.{fn} d) =
        ({digit} : Fin 16) :: littleDouble {carry} (hexadecimalDigitsTo d)
      exact congrArg (List.cons ({digit} : Fin 16)) ih.{ih}
'''
s=s[:start]+block+'\n'+s[end:]
for suffix in ['rect','rec']:
 start=s.index('theorem uint_'+suffix+'_agrees')
 end=s.index('\ndef digitInduction',start) if suffix=='rec' else s.index('theorem uint_rec_agrees',start)
 block=f'''theorem uint_{suffix}_agrees (P : List (Fin 16) → {'Sort u' if suffix=='rect' else 'Type'})
    (nil : P []) (cons : ∀ d ds, P ds → P (d :: ds)) (d : U) :
    Rocq.Corelib.Init.Hexadecimal.uint_{suffix} (fun d => P (hexadecimalDigitsTo d)) nil
'''
 for k in range(16):block+=f'      (fun d ih => cons {k} (hexadecimalDigitsTo d) ih)\n'
 block+='      d = digitsRec P nil cons (hexadecimalDigitsTo d) := by\n  induction d with\n  | Nil => rfl\n'
 for k in range(16):block+=f'  | D{k:x} d ih => exact congrArg (cons {k} (hexadecimalDigitsTo d)) ih\n'
 s=s[:start]+block+'\n'+s[end:]
s=s.replace('h7 h8 h9 d','h7 h8 h9 ha hb hc hd he hf d')
s=s.replace('  | D9 d ih => exact h9 d ih','\n'.join(f'  | D{k:x} d ih => exact h{k:x} d ih' for k in range(9,16)))
s=s.replace('= [0,9,1] := rfl','= [10,2,1] := rfl')
for base in ['uint','signed_int']:
 for direction in ['bl','lb']:
  s=s.replace('Rocq.Corelib.Init.Hexadecimal.internal_'+base+'_dec_'+direction+'.statement','Rocq.Corelib.Init.Hexadecimal.internal_'+base+'_dec_'+direction+'0.statement')
s=s.replace('(fun x xs =>','(fun _x xs =>')
import json
names=sorted({sp['native_target'] for sp in json.loads((W/'certificates.json').read_text()) if sp['profile']=='HexadecimalRepresentation'})
assert len(names)>0
footer=(W/'proofs/DecimalRepresentation.lean').read_text().split('\nopen Lean Meta Elab Command')[1]
footer=re.sub(r'for name in \[.*\] do','for name in '+json.dumps(names)+' do',footer)
s+='\nopen Lean Meta Elab Command'+footer
(W/'proofs/HexadecimalRepresentation.lean').write_text(s)
