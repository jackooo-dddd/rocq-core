"""Recheck shared positive square-root proofs in the actual PosDef closure.

IntDef includes Pos.sqrtrem but omits the Pos.sqrt root. The two exported
closures reuse module names, so they must not be imported together. Reuse
proof text here, then independently kernel-check against PosDef; no source
declaration is invented and duplicated helper certificates are not counted.
"""
from pathlib import Path
W=Path(__file__).resolve().parent
s=(W/'proofs/BinarySqrtRem.lean').read_text()
body=s[s.index('abbrev SqrtPair'):s.index('def zSqrtRemNative')]
o=(W/'proofs/BinaryOrder.lean').read_text()
order=o[o.index('def compareCont'):o.index('theorem positive_div2_agrees')]
order+=o[o.index('theorem compare_leb'):o.index('theorem n_compare_agrees')]
head="""-- Generated by generate_positive_sqrt.py; independently checked against PosDef.
import BinaryMask
import Init.Data.Nat.Sqrt.Lemmas
set_option autoImplicit false
set_option linter.unusedSimpArgs false
noncomputable section
namespace NativeBridge.Incremental.BinaryPositiveSqrt
open NativeBridge BinaryMask
"""
tail="""
theorem positive_sqrt_agrees (p : RPositive) :
    positiveTo (Rocq.Corelib.BinNums.PosDef.Pos.sqrt p) = Nat.sqrt (positiveTo p) := by
  have h := sqrtrem_agrees p
  have hh := congrArg Prod.fst h
  cases hx : Rocq.Corelib.BinNums.PosDef.Pos.sqrtrem p with
  | pair s r =>
    rw [hx] at hh
    simpa [Rocq.Corelib.BinNums.PosDef.Pos.sqrt,hx,sqrtPairTo,sqrtRemNative,prodTo] using hh

theorem example_positive_sqrt_12345 :
    positiveTo (Rocq.Corelib.BinNums.PosDef.Pos.sqrt (positiveOf 12345)) = 111 := by
  rw [positive_sqrt_agrees,positive_to_of _ (by decide)]
  decide +kernel
end NativeBridge.Incremental.BinaryPositiveSqrt
"""
footer=s[s.index('\nopen Lean Meta Elab Command'):]
import re
footer=re.sub(r'for name in \[.*\] do','for name in ["Nat.sqrt"] do',footer)
(W/'proofs/BinaryPositiveSqrt.lean').write_text(head+order+body+tail+footer)
